-- Complaints (FR-21) and their moderation (FR-22). A complaint is filed by a user against another user and relates
-- to exactly one booking or one listing; it never hides anything by itself (only an admin block does, FR-20).
CREATE TABLE complaints (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id       BIGINT        NOT NULL,
    against_user_id BIGINT        NOT NULL,
    booking_id      BIGINT,
    equipment_id    BIGINT,
    description     VARCHAR(1000) NOT NULL,
    status          VARCHAR(10)   NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at      TIMESTAMP WITH TIME ZONE,
    decided_by      BIGINT,
    CONSTRAINT fk_complaints_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT fk_complaints_against FOREIGN KEY (against_user_id) REFERENCES users (id),
    CONSTRAINT fk_complaints_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_complaints_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id),
    CONSTRAINT fk_complaints_decided_by FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_complaints_one_subject CHECK ((booking_id IS NULL AND equipment_id IS NOT NULL)
        OR (booking_id IS NOT NULL AND equipment_id IS NULL)),
    CONSTRAINT ck_complaints_parties CHECK (author_id <> against_user_id),
    CONSTRAINT ck_complaints_status CHECK (status IN ('NEW', 'RESOLVED', 'REJECTED')),
    CONSTRAINT ck_complaints_decision CHECK ((status = 'NEW' AND decided_at IS NULL)
        OR (status <> 'NEW' AND decided_at IS NOT NULL))
);

CREATE INDEX ix_complaints_against_status ON complaints (against_user_id, status);
CREATE INDEX ix_complaints_status_created ON complaints (status, created_at);
CREATE INDEX ix_complaints_author ON complaints (author_id);
