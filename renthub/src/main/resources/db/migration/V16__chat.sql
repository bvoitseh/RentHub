-- Chat between two users (D-57). One conversation per pair of users, stored with the smaller id first so the pair is
-- unique. Each side keeps the id of the last message it has read (unread = newer messages from the other side) and
-- the id of the last message it was e-mailed about (at most one e-mail per conversation until the side reads it).
CREATE TABLE conversations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_low_id          BIGINT NOT NULL,
    user_high_id         BIGINT NOT NULL,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL,
    last_message_at      TIMESTAMP WITH TIME ZONE,
    low_last_read_id     BIGINT NOT NULL DEFAULT 0,
    high_last_read_id    BIGINT NOT NULL DEFAULT 0,
    low_notified_id      BIGINT NOT NULL DEFAULT 0,
    high_notified_id     BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_conversations_low FOREIGN KEY (user_low_id) REFERENCES users (id),
    CONSTRAINT fk_conversations_high FOREIGN KEY (user_high_id) REFERENCES users (id),
    CONSTRAINT ck_conversations_pair CHECK (user_low_id < user_high_id),
    CONSTRAINT uq_conversations_pair UNIQUE (user_low_id, user_high_id)
);

CREATE INDEX ix_conversations_high ON conversations (user_high_id);

-- A message is text, or a file / voice / video attachment stored in the object storage under a private key.
CREATE TABLE chat_messages (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id   BIGINT        NOT NULL,
    sender_id         BIGINT        NOT NULL,
    kind              VARCHAR(10)   NOT NULL,
    body              VARCHAR(4000),
    attachment_key    VARCHAR(255),
    attachment_name   VARCHAR(255),
    attachment_type   VARCHAR(100),
    attachment_size   BIGINT,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_chat_messages_conversation FOREIGN KEY (conversation_id) REFERENCES conversations (id),
    CONSTRAINT fk_chat_messages_sender FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT ck_chat_messages_kind CHECK (kind IN ('TEXT', 'FILE', 'VOICE', 'VIDEO')),
    CONSTRAINT ck_chat_messages_content CHECK (
        (kind = 'TEXT' AND body IS NOT NULL AND attachment_key IS NULL)
        OR (kind <> 'TEXT' AND attachment_key IS NOT NULL AND attachment_name IS NOT NULL
            AND attachment_type IS NOT NULL AND attachment_size > 0))
);

CREATE INDEX ix_chat_messages_conversation ON chat_messages (conversation_id, id);
CREATE INDEX ix_chat_messages_created ON chat_messages (created_at);
