-- Equipment categories with their rental season in months 1-12 (FR-17 later); a season may wrap over New Year
-- (season_from > season_to, e.g. 11 -> 3). The initial list is reference data the catalogue needs (DECISIONS.md D-31);
-- the admin manages categories later (FR-22).
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    season_from INTEGER      NOT NULL,
    season_to   INTEGER      NOT NULL,
    CONSTRAINT uq_categories_name UNIQUE (name),
    CONSTRAINT ck_categories_season CHECK (season_from BETWEEN 1 AND 12 AND season_to BETWEEN 1 AND 12)
);

