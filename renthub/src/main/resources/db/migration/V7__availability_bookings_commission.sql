-- Commission rates (FR-10, FR-22) as versioned rows: the rate in force at a moment is the newest row whose
-- valid_from is not later than that moment. Every booking keeps a reference to the rate it was priced with (D-37).
CREATE TABLE commission_rates (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate       NUMERIC(5, 2) NOT NULL,
    valid_from TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_commission_rates_valid_from UNIQUE (valid_from),
    CONSTRAINT ck_commission_rates_rate CHECK (rate >= 0 AND rate <= 100)
);

-- The initial rate is the one the skeleton stored in the (now unused) settings table.
INSERT INTO commission_rates (rate, valid_from, created_at)
SELECT fee_rate, TIMESTAMP WITH TIME ZONE '2026-01-01 00:00:00+02:00', CURRENT_TIMESTAMP FROM settings;

-- Periods the owner closed for rental (FR-8); a block closes every unit of the listing (FR-9).
CREATE TABLE availability_blocks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT       NOT NULL,
    date_from    DATE         NOT NULL,
    date_to      DATE         NOT NULL,
    reason       VARCHAR(200),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_availability_blocks_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id),
    CONSTRAINT ck_availability_blocks_dates CHECK (date_to >= date_from)
);

CREATE INDEX ix_availability_blocks_equipment ON availability_blocks (equipment_id, date_from, date_to);

-- Booking requests and their lifecycle (FR-10...FR-15b). Prices are frozen at request time.
CREATE TABLE bookings (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id       BIGINT        NOT NULL,
    renter_id          BIGINT        NOT NULL,
    units              INTEGER       NOT NULL,
    date_from          DATE          NOT NULL,
    date_to            DATE          NOT NULL,
    handover           VARCHAR(10)   NOT NULL,
    price_per_day      NUMERIC(10, 2) NOT NULL,
    total_price        NUMERIC(12, 2) NOT NULL,
    commission_rate_id BIGINT        NOT NULL,
    commission         NUMERIC(12, 2) NOT NULL,
    status             VARCHAR(10)   NOT NULL,
    expired            BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    decided_at         TIMESTAMP WITH TIME ZONE,
    completed_at       TIMESTAMP WITH TIME ZONE,
    cancelled_by       VARCHAR(10),
    cancel_reason      VARCHAR(500),
    CONSTRAINT fk_bookings_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id),
    CONSTRAINT fk_bookings_renter FOREIGN KEY (renter_id) REFERENCES users (id),
    CONSTRAINT fk_bookings_commission_rate FOREIGN KEY (commission_rate_id) REFERENCES commission_rates (id),
    CONSTRAINT ck_bookings_units CHECK (units >= 1),
    CONSTRAINT ck_bookings_dates CHECK (date_to >= date_from),
    CONSTRAINT ck_bookings_prices CHECK (price_per_day > 0 AND total_price > 0 AND commission >= 0),
    CONSTRAINT ck_bookings_handover CHECK (handover IN ('PICKUP', 'DELIVERY')),
    CONSTRAINT ck_bookings_status CHECK (status IN ('NEW', 'CONFIRMED', 'REJECTED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT ck_bookings_cancelled_by CHECK (cancelled_by IS NULL OR cancelled_by IN ('RENTER', 'OWNER', 'ADMIN'))
);

CREATE INDEX ix_bookings_equipment_status_dates ON bookings (equipment_id, status, date_from, date_to);
CREATE INDEX ix_bookings_renter_status ON bookings (renter_id, status);
CREATE INDEX ix_bookings_status_created ON bookings (status, created_at);
