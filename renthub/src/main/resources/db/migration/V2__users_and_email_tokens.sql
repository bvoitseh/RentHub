-- Accounts (FR-1, FR-1a, FR-2, FR-3, FR-3c) and single-use e-mail tokens (FR-1, FR-3a, NFR-5).
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100)  NOT NULL,
    email          VARCHAR(255)  NOT NULL,
    email_verified BOOLEAN       NOT NULL DEFAULT FALSE,
    phone          VARCHAR(20),
    password_hash  VARCHAR(100)  NOT NULL,
    role           VARCHAR(10)   NOT NULL,
    city           VARCHAR(100),
    geo_consent    BOOLEAN       NOT NULL DEFAULT FALSE,
    blocked        BOOLEAN       NOT NULL DEFAULT FALSE,
    deactivated_at TIMESTAMP WITH TIME ZONE,
    owner_type     VARCHAR(10),
    company_name   VARCHAR(200),
    edrpou         VARCHAR(8),
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('RENTER', 'OWNER', 'ADMIN')),
    CONSTRAINT ck_users_owner_type CHECK (owner_type IS NULL OR owner_type IN ('PRIVATE', 'COMPANY')),
    CONSTRAINT ck_users_owner_type_role CHECK (owner_type IS NULL OR role = 'OWNER'),
    CONSTRAINT ck_users_company CHECK (owner_type <> 'COMPANY' OR (company_name IS NOT NULL AND edrpou IS NOT NULL)),
    CONSTRAINT ck_users_edrpou CHECK (edrpou IS NULL OR LENGTH(edrpou) = 8)
);

CREATE TABLE email_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    type       VARCHAR(20)  NOT NULL,
    token_hash VARCHAR(64)  NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    used_at    TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_email_tokens_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_email_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_email_tokens_type CHECK (type IN ('VERIFY_EMAIL', 'RESET_PASSWORD'))
);

CREATE INDEX ix_email_tokens_user_type ON email_tokens (user_id, type);
