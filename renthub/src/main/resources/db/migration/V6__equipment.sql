-- Listings (FR-4, FR-4b, FR-4c) and their photos (FR-4a: only storage keys, the files live in object storage).
CREATE TABLE equipment (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id           BIGINT        NOT NULL,
    category_id        BIGINT        NOT NULL,
    title              VARCHAR(120)  NOT NULL,
    description        VARCHAR(4000) NOT NULL,
    item_condition     VARCHAR(10)   NOT NULL,
    price_per_day      NUMERIC(10, 2) NOT NULL,
    quantity           INTEGER       NOT NULL,
    min_days           INTEGER       NOT NULL,
    max_days           INTEGER,
    pickup_available   BOOLEAN       NOT NULL,
    delivery_available BOOLEAN       NOT NULL,
    delivery_note      VARCHAR(500),
    address            VARCHAR(300)  NOT NULL,
    lat                DOUBLE PRECISION NOT NULL,
    lon                DOUBLE PRECISION NOT NULL,
    status             VARCHAR(10)   NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_equipment_owner FOREIGN KEY (owner_id) REFERENCES users (id),
    CONSTRAINT fk_equipment_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_equipment_condition CHECK (item_condition IN ('NEW', 'EXCELLENT', 'GOOD', 'FAIR')),
    CONSTRAINT ck_equipment_status CHECK (status IN ('ACTIVE', 'ARCHIVED', 'BLOCKED')),
    CONSTRAINT ck_equipment_price CHECK (price_per_day > 0),
    CONSTRAINT ck_equipment_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_equipment_days CHECK (min_days >= 1 AND (max_days IS NULL OR max_days >= min_days)),
    CONSTRAINT ck_equipment_handover CHECK (pickup_available OR delivery_available),
    CONSTRAINT ck_equipment_coordinates CHECK (lat BETWEEN -90 AND 90 AND lon BETWEEN -180 AND 180)
);

CREATE INDEX ix_equipment_status_category ON equipment (status, category_id);
CREATE INDEX ix_equipment_owner ON equipment (owner_id);
CREATE INDEX ix_equipment_price ON equipment (price_per_day);

CREATE TABLE equipment_photos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id BIGINT       NOT NULL,
    storage_key  VARCHAR(200) NOT NULL,
    position     INTEGER      NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_equipment_photos_equipment FOREIGN KEY (equipment_id) REFERENCES equipment (id),
    CONSTRAINT uq_equipment_photos_key UNIQUE (storage_key),
    CONSTRAINT ck_equipment_photos_position CHECK (position BETWEEN 0 AND 4)
);

CREATE INDEX ix_equipment_photos_equipment ON equipment_photos (equipment_id, position);
