-- Reference tables for structured addresses (FR-1, FR-4, FR-16, FR-23; DECISIONS.md D-48): regions of Ukraine and
-- their settlements from OpenStreetMap, with the legal status from Wikidata. Rows are keyed by the OSM id so a refresh
-- can match them; removed ones become inactive (hidden from search) and are never deleted while referenced.
CREATE TABLE regions (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_id   BIGINT       NOT NULL,
    iso_code VARCHAR(6)   NOT NULL,
    name     VARCHAR(100) NOT NULL,
    active   BOOLEAN      DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_regions_osm_id UNIQUE (osm_id),
    CONSTRAINT uq_regions_iso_code UNIQUE (iso_code)
);

CREATE TABLE settlements (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    osm_id      BIGINT           NOT NULL,
    region_id   BIGINT           NOT NULL,
    name        VARCHAR(120)     NOT NULL,
    -- lower case, apostrophes removed: the key of the case- and apostrophe-insensitive prefix search
    search_name VARCHAR(120)     NOT NULL,
    -- legal status: CITY (місто), TOWN (селище), VILLAGE (село); NULL when Wikidata gives no clear status
    status      VARCHAR(10),
    district    VARCHAR(120),
    community   VARCHAR(120),
    -- suggestion text, e.g. «с. Миколаївка, Лихівська громада, Кам'янський р-н»
    label       VARCHAR(300)     NOT NULL,
    lat         DOUBLE PRECISION NOT NULL,
    lon         DOUBLE PRECISION NOT NULL,
    postal_code VARCHAR(5),
    active      BOOLEAN          DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_settlements_osm_id UNIQUE (osm_id),
    CONSTRAINT fk_settlements_region FOREIGN KEY (region_id) REFERENCES regions (id),
    CONSTRAINT ck_settlements_status CHECK (status IS NULL OR status IN ('CITY', 'TOWN', 'VILLAGE')),
    CONSTRAINT ck_settlements_coordinates CHECK (lat BETWEEN -90 AND 90 AND lon BETWEEN -180 AND 180)
);

CREATE INDEX ix_settlements_region_search ON settlements (region_id, search_name);
