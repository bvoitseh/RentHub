-- Two-sided reviews after a completed rental (FR-18) and the rating they feed (FR-19).
-- One review per side per booking; hidden (published_at NULL) until both sides reviewed or the window expired.
CREATE TABLE reviews (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id   BIGINT        NOT NULL,
    author_id    BIGINT        NOT NULL,
    target_id    BIGINT        NOT NULL,
    rating       INTEGER       NOT NULL,
    comment      VARCHAR(1000) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    reply        VARCHAR(1000),
    replied_at   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_reviews_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_reviews_author FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT fk_reviews_target FOREIGN KEY (target_id) REFERENCES users (id),
    CONSTRAINT uq_reviews_booking_author UNIQUE (booking_id, author_id),
    CONSTRAINT ck_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_reviews_parties CHECK (author_id <> target_id),
    CONSTRAINT ck_reviews_reply CHECK ((reply IS NULL AND replied_at IS NULL)
        OR (reply IS NOT NULL AND replied_at IS NOT NULL AND published_at IS NOT NULL))
);

CREATE INDEX ix_reviews_target_published ON reviews (target_id, published_at);
CREATE INDEX ix_reviews_unpublished ON reviews (published_at, booking_id);

-- FR-19 rating from published reviews, kept on the user so cards and the rating sort need no aggregation:
-- sum and count are exact, the average is derived from them (NULL while there are no published reviews).
ALTER TABLE users ADD COLUMN rating_sum INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE users ADD COLUMN review_count INTEGER DEFAULT 0 NOT NULL;
ALTER TABLE users ADD COLUMN rating_avg NUMERIC(3, 2);
